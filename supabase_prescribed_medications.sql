-- Prescription periods per user. This table deliberately has no relationship
-- with daily habits or legacy medication intake events.
create table if not exists public.prescribed_medications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) > 0),
  active_ingredient text,
  dose text,
  frequency text,
  start_date date not null,
  end_date date,
  status text not null default 'active' check (status in ('active', 'finished', 'suspended')),
  reason text,
  prescriber text,
  instructions text,
  notes text,
  suspension_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_date is null or end_date >= start_date),
  check (status = 'active' or end_date is not null)
);

create index if not exists prescribed_medications_user_dates_idx
on public.prescribed_medications (user_id, start_date desc, end_date desc);

create index if not exists prescribed_medications_user_status_idx
on public.prescribed_medications (user_id, status);

create or replace function public.set_prescribed_medication_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists prescribed_medications_set_updated_at on public.prescribed_medications;
create trigger prescribed_medications_set_updated_at
before update on public.prescribed_medications
for each row execute function public.set_prescribed_medication_updated_at();

alter table public.prescribed_medications enable row level security;

drop policy if exists prescribed_medications_select_own on public.prescribed_medications;
create policy prescribed_medications_select_own
on public.prescribed_medications for select
using (auth.uid() = user_id);

drop policy if exists prescribed_medications_insert_own on public.prescribed_medications;
create policy prescribed_medications_insert_own
on public.prescribed_medications for insert
with check (auth.uid() = user_id);

drop policy if exists prescribed_medications_update_own on public.prescribed_medications;
create policy prescribed_medications_update_own
on public.prescribed_medications for update
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists prescribed_medications_delete_own on public.prescribed_medications;
create policy prescribed_medications_delete_own
on public.prescribed_medications for delete
using (auth.uid() = user_id);

grant select, insert, update, delete on table public.prescribed_medications to authenticated;
grant usage, select on sequence public.prescribed_medications_id_seq to authenticated;

