-- Health context for habits. All changes are additive and preserve legacy
-- habit_checks values (0 = not completed, 1 = completed).
create table if not exists public.health_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(trim(title)) > 0),
  type text not null check (type in ('injury', 'pain', 'illness', 'fatigue', 'stress', 'accident', 'medical_visit', 'emotional_event', 'other')),
  start_date date not null,
  end_date date,
  status text not null default 'active' check (status in ('active', 'improving', 'resolved')),
  severity text check (severity is null or severity in ('mild', 'moderate', 'severe')),
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_date is null or end_date >= start_date)
);

create index if not exists health_events_user_status_dates_idx
on public.health_events (user_id, status, start_date desc);

create table if not exists public.health_event_habits (
  user_id uuid not null references auth.users(id) on delete cascade,
  health_event_id bigint not null references public.health_events(id) on delete cascade,
  habit_id bigint not null references public.habits(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (health_event_id, habit_id)
);

create index if not exists health_event_habits_user_habit_idx
on public.health_event_habits (user_id, habit_id);

create table if not exists public.daily_notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  note_date date not null,
  comment text not null check (char_length(trim(comment)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, note_date)
);

alter table public.habit_checks add column if not exists comment text;
alter table public.habit_checks add column if not exists reason text;
alter table public.habit_checks add column if not exists health_event_id bigint references public.health_events(id) on delete set null;
alter table public.habit_checks add column if not exists updated_at timestamptz not null default now();

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'habit_checks_health_event_id_fkey'
      and conrelid = 'public.habit_checks'::regclass
  ) then
    alter table public.habit_checks
      add constraint habit_checks_health_event_id_fkey
      foreign key (health_event_id) references public.health_events(id) on delete set null;
  end if;
end
$$;

alter table public.habit_checks drop constraint if exists habit_checks_status_check;
alter table public.habit_checks
  add constraint habit_checks_status_check check (status in (0, 1, 2));
alter table public.habit_checks drop constraint if exists habit_checks_reason_check;
alter table public.habit_checks
  add constraint habit_checks_reason_check check (
    reason is null or reason in ('health', 'injury', 'fatigue', 'stress', 'lack_of_time', 'travel', 'social_event', 'emotional_event', 'not_applicable', 'other')
  );

create index if not exists habit_checks_health_event_idx
on public.habit_checks (health_event_id) where health_event_id is not null;

create or replace function public.set_health_context_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists health_events_set_updated_at on public.health_events;
create trigger health_events_set_updated_at before update on public.health_events
for each row execute function public.set_health_context_updated_at();
drop trigger if exists daily_notes_set_updated_at on public.daily_notes;
create trigger daily_notes_set_updated_at before update on public.daily_notes
for each row execute function public.set_health_context_updated_at();
drop trigger if exists habit_checks_set_updated_at on public.habit_checks;
create trigger habit_checks_set_updated_at before update on public.habit_checks
for each row execute function public.set_health_context_updated_at();

alter table public.health_events enable row level security;
alter table public.health_event_habits enable row level security;
alter table public.daily_notes enable row level security;

drop policy if exists health_events_own on public.health_events;
create policy health_events_own on public.health_events for all
using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists health_event_habits_own on public.health_event_habits;
create policy health_event_habits_own on public.health_event_habits for all
using (auth.uid() = user_id)
with check (
  auth.uid() = user_id
  and exists (select 1 from public.health_events e where e.id = health_event_id and e.user_id = auth.uid())
  and exists (select 1 from public.habits h where h.id = habit_id and h.user_id = auth.uid())
);

drop policy if exists daily_notes_own on public.daily_notes;
create policy daily_notes_own on public.daily_notes for all
using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Extend habit-check write policies so an optional linked event must belong to
-- the same authenticated user.
drop policy if exists habit_checks_insert_own on public.habit_checks;
create policy habit_checks_insert_own on public.habit_checks for insert
with check (
  auth.uid() = user_id
  and exists (select 1 from public.habits h where h.id = habit_id and h.user_id = auth.uid())
  and (health_event_id is null or exists (select 1 from public.health_events e where e.id = health_event_id and e.user_id = auth.uid()))
);

drop policy if exists habit_checks_update_own on public.habit_checks;
create policy habit_checks_update_own on public.habit_checks for update
using (auth.uid() = user_id)
with check (
  auth.uid() = user_id
  and exists (select 1 from public.habits h where h.id = habit_id and h.user_id = auth.uid())
  and (health_event_id is null or exists (select 1 from public.health_events e where e.id = health_event_id and e.user_id = auth.uid()))
);

grant select, insert, update, delete on public.health_events, public.health_event_habits, public.daily_notes to authenticated;
grant usage, select on sequence public.health_events_id_seq, public.daily_notes_id_seq to authenticated;
