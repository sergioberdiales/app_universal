-- Reversible habit archiving with a required closed-list reason.
-- Activity periods use [started_on, ended_on): the start date is included and
-- the end date is the first day on which the habit is no longer active.

alter table public.habits add column if not exists archived_at timestamptz;
alter table public.habits add column if not exists archive_reason text;

update public.habits
set archived_at = coalesce(archived_at, now()),
    archive_reason = coalesce(archive_reason, 'other')
where is_active = false;

alter table public.habits drop constraint if exists habits_archive_reason_check;
alter table public.habits
  add constraint habits_archive_reason_check check (
    archive_reason is null or archive_reason in (
      'consolidated',
      'goal_achieved',
      'no_longer_relevant',
      'replaced',
      'circumstances',
      'created_by_mistake',
      'other'
    )
  );

alter table public.habits drop constraint if exists habits_archive_state_check;
alter table public.habits
  add constraint habits_archive_state_check check (
    (is_active and archived_at is null and archive_reason is null)
    or
    (not is_active and archived_at is not null and archive_reason is not null)
  );

create table if not exists public.habit_activity_periods (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  habit_id bigint not null references public.habits(id) on delete cascade,
  started_on date not null,
  ended_on date,
  archive_reason text,
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  check (ended_on is null or ended_on >= started_on),
  check (
    (ended_on is null and archive_reason is null and archived_at is null)
    or
    (ended_on is not null and archive_reason is not null and archived_at is not null)
  ),
  check (
    archive_reason is null or archive_reason in (
      'consolidated',
      'goal_achieved',
      'no_longer_relevant',
      'replaced',
      'circumstances',
      'created_by_mistake',
      'other'
    )
  )
);

create index if not exists habit_activity_periods_user_habit_dates_idx
on public.habit_activity_periods (user_id, habit_id, started_on, ended_on);

create unique index if not exists habit_activity_periods_one_open_idx
on public.habit_activity_periods (habit_id)
where ended_on is null;

insert into public.habit_activity_periods (
  user_id,
  habit_id,
  started_on,
  ended_on,
  archive_reason,
  archived_at
)
select
  h.user_id,
  h.id,
  h.created_at::date,
  case when h.is_active then null else h.archived_at::date end,
  case when h.is_active then null else h.archive_reason end,
  case when h.is_active then null else h.archived_at end
from public.habits h
where not exists (
  select 1
  from public.habit_activity_periods p
  where p.habit_id = h.id
);

create or replace function public.create_initial_habit_activity_period()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  insert into public.habit_activity_periods (user_id, habit_id, started_on)
  values (new.user_id, new.id, new.created_at::date);
  return new;
end;
$$;

drop trigger if exists habits_create_activity_period on public.habits;
create trigger habits_create_activity_period
after insert on public.habits
for each row execute function public.create_initial_habit_activity_period();

alter table public.habit_activity_periods enable row level security;

drop policy if exists habit_activity_periods_select_own on public.habit_activity_periods;
create policy habit_activity_periods_select_own
on public.habit_activity_periods
for select
using (auth.uid() = user_id);

drop policy if exists habit_activity_periods_insert_own on public.habit_activity_periods;
create policy habit_activity_periods_insert_own
on public.habit_activity_periods
for insert
with check (
  auth.uid() = user_id
  and exists (
    select 1 from public.habits h
    where h.id = habit_id and h.user_id = auth.uid()
  )
);

drop policy if exists habit_activity_periods_update_own on public.habit_activity_periods;
create policy habit_activity_periods_update_own
on public.habit_activity_periods
for update
using (auth.uid() = user_id)
with check (
  auth.uid() = user_id
  and exists (
    select 1 from public.habits h
    where h.id = habit_id and h.user_id = auth.uid()
  )
);

create or replace function public.archive_habit(
  p_habit_id bigint,
  p_reason text,
  p_effective_on date default current_date
)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_archived_at timestamptz := now();
begin
  if p_reason is null or p_reason not in (
    'consolidated',
    'goal_achieved',
    'no_longer_relevant',
    'replaced',
    'circumstances',
    'created_by_mistake',
    'other'
  ) then
    raise exception 'Motivo de archivo no valido.';
  end if;

  update public.habits
  set is_active = false,
      archived_at = v_archived_at,
      archive_reason = p_reason
  where id = p_habit_id
    and user_id = auth.uid()
    and is_active = true;

  if not found then
    raise exception 'El habito no existe o ya esta archivado.';
  end if;

  update public.habit_activity_periods
  set ended_on = p_effective_on,
      archived_at = v_archived_at,
      archive_reason = p_reason
  where habit_id = p_habit_id
    and user_id = auth.uid()
    and ended_on is null
    and started_on <= p_effective_on;

  if not found then
    raise exception 'No se encontro un periodo activo para el habito.';
  end if;
end;
$$;

create or replace function public.reactivate_habit(
  p_habit_id bigint,
  p_effective_on date default current_date
)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_user_id uuid;
begin
  update public.habits
  set is_active = true,
      archived_at = null,
      archive_reason = null
  where id = p_habit_id
    and user_id = auth.uid()
    and is_active = false
  returning user_id into v_user_id;

  if not found then
    raise exception 'El habito no existe o ya esta activo.';
  end if;

  insert into public.habit_activity_periods (user_id, habit_id, started_on)
  values (v_user_id, p_habit_id, p_effective_on);
end;
$$;

grant select, insert, update on public.habit_activity_periods to authenticated;
grant usage, select on sequence public.habit_activity_periods_id_seq to authenticated;
revoke all on function public.archive_habit(bigint, text, date) from public, anon;
revoke all on function public.reactivate_habit(bigint, date) from public, anon;
grant execute on function public.archive_habit(bigint, text, date) to authenticated;
grant execute on function public.reactivate_habit(bigint, date) to authenticated;
